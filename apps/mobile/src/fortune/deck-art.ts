export function suitSymbol(cardKey: string): string {
  if (cardKey.startsWith('cups-')) return '◇';
  if (cardKey.startsWith('wands-')) return '│';
  if (cardKey.startsWith('swords-')) return '†';
  if (cardKey.startsWith('pentacles-')) return '⬟';
  return '✦';
}
